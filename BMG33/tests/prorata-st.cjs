const fs=require('fs');const vm=require('vm');const assert=require('assert');
const src=fs.readFileSync(__dirname+'/../src/App.jsx','utf8');
const a=src.indexOf('function generateMonthLabels('), b=src.indexOf('const TABS =');
const ctx=vm.createContext({Date,Number,Array,Object,Boolean,String,Math});vm.runInContext(src.slice(a,b),ctx);
const normalize=vm.runInContext('normalizeProjectData',ctx);
const deduction=vm.runInContext('stProrataAmount',ctx);
const net=vm.runInContext('stNetAfterProrata',ctx);
const base=vm.runInContext('stProrataBase',ctx);
const st={initialMarket:100000,modifications:10000,toRegularize:5000,provision:2000,prorataRate:2};
assert.strictEqual(base(st),115000);
assert.strictEqual(deduction(st),2300);
assert.strictEqual(net(st),112700);
assert.strictEqual(deduction({...st,prorataRate:3.5}),4025);
assert.strictEqual(deduction({...st,prorataRate:0}),0);
const old=normalize({subContractors:[{id:10,code:'STX',initialMarket:100000,modifications:10000,toRegularize:5000,provision:2000,radMonthly:[]}]});
assert.strictEqual(old.subContractors[0].prorataRate,2);
assert.strictEqual(deduction(old.subContractors[0]),2300);
const saved=normalize(JSON.parse(JSON.stringify({...old,subContractors:old.subContractors.map(st=>({...st,prorataRate:4}))})));
assert.strictEqual(saved.subContractors[0].prorataRate,4);
assert.strictEqual(deduction(saved.subContractors[0]),4600);
assert(src.includes('aria-label={`Taux de prorata de ${st.company}`}'));
console.log('PASS: 10 contrôles prorata ST');
