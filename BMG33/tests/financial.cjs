const fs = require('fs');
const vm = require('vm');
const assert = require('assert');
const s = fs.readFileSync(__dirname+'/../src/App.jsx','utf8');
const start = s.indexOf('function generateMonthLabels(');
const end = s.indexOf('const TABS =');
const context = vm.createContext({Date, Number, Array, Object, Boolean, String, Math});
vm.runInContext(s.slice(start,end),context);
const normalize = vm.runInContext('normalizeProjectData',context);
const stTotal = vm.runInContext('stMarketTotal',context);
const orderSum = vm.runInContext('stOrderSum',context);
const p = normalize({});
assert(p.imputationCodes.some(c=>c.code==='PRORATA'));
assert.strictEqual(p.subContractors[1].modifications,12000);
assert.strictEqual(p.subContractors[1].toRegularize,5000);
assert.strictEqual(p.subContractors[1].modificationOrders.length,1);
assert.strictEqual(stTotal(p.subContractors[1]),467000);
const legacy = normalize({subContractors:[{id:123,code:'STX',company:'TEST',initialMarket:90000,modifications:2500,toRegularize:1000,provision:500,radMonthly:[10]}],imputationCodes:[{code:'PRORATA',family:'Frais divers',pu:7500,qty:1,locked:false}],prorataBudget:0});
assert.strictEqual(legacy.subContractors[0].modificationOrders[0].amount,2500);
assert.strictEqual(legacy.subContractors[0].pendingOrders[0].amount,1000);
assert.strictEqual(stTotal(legacy.subContractors[0]),93500);
assert.strictEqual(legacy.imputationCodes.find(c=>c.code==='PRORATA').pu,7500);
assert.strictEqual(legacy.imputationCodes.find(c=>c.code==='PRORATA').locked,false);
legacy.subContractors[0].modificationOrders.push({id:'om2',reference:'OM-02',amount:-300});
legacy.subContractors[0].modifications=orderSum(legacy.subContractors[0].modificationOrders);
assert.strictEqual(stTotal(legacy.subContractors[0]),93200);
const roundtrip=normalize(JSON.parse(JSON.stringify(legacy)));
assert.strictEqual(roundtrip.subContractors[0].modificationOrders.length,2);
assert.strictEqual(roundtrip.subContractors[0].modifications,2200);
const generate = vm.runInContext('generateMonthLabels',context);
assert.strictEqual(generate('2025-01-01','2028-12-31').months.length,48);
console.log('PASS: 12 vérifications : migration, montants ST, OM, régularisations, PRORATA, persistance, 48 mois.');
