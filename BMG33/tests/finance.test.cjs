const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const src = fs.readFileSync(path.join(__dirname, '../src/App.jsx'), 'utf8');
const start = src.indexOf('const sumSTOrders');
const end = src.indexOf('function normalizeProjectData', start);
assert(start >= 0 && end > start, 'Calcul ST introuvable');
const context = {};
vm.createContext(context);
vm.runInContext(src.slice(start, end) + '\nthis.calc = stFinancials;', context);
const calc = context.calc;
const st = {initialMarket:90000, modificationOrders:[{amount:12000},{amount:-2000}],pendingOrders:[{amount:5000}],provision:3000};
assert.equal(calc(st).signedMarket, 100000, 'Marché contractualisé');
assert.equal(calc(st).forecastMarket, 105000, 'Prévisionnel hors provision');
assert.equal(calc(st).forecastWithProvision, 108000, 'Prévisionnel avec provision');
st.modificationOrders[0].amount = 14000;
assert.equal(calc(st).forecastMarket, 107000, 'Modification OM');
st.pendingOrders = [];
assert.equal(calc(st).forecastMarket, 102000, 'Suppression à régulariser');
assert(src.includes('const legacyProrataBudget = oldProrataCode ?'), 'Priorité budget PRORATA');
assert(src.includes('visibleMonthEntries.map(({index: idx}) => <td key={idx} className="px-4 py-3 text-center text-sky-700"'), 'Filtre mois dépenses');
console.log('7 contrôles BMG réussis.');
